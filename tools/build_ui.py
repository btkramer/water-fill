#!/usr/bin/env python3
"""Gzip web/index.html into WaterFill_v2/web_assets.h (PROGMEM byte array).
Run after editing the UI:  python3 tools/build_ui.py"""
import gzip, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "WaterFill_v2", "web_assets.h")

raw = open(src, "rb").read()
gz = gzip.compress(raw, 9, mtime=0)
lines = []
for i in range(0, len(gz), 24):
    lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 24]) + ",")
with open(dst, "w") as f:
    f.write("// Generated by tools/build_ui.py from web/index.html. Do not edit.\n#pragma once\n#include <Arduino.h>\n")
    f.write("static const size_t WEB_INDEX_GZ_LEN = %d;\n" % len(gz))
    f.write("static const uint8_t WEB_INDEX_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n")
print("index.html: %d bytes -> %d gzipped" % (len(raw), len(gz)))
